/**
 * 把原始元组行映射成带类型的对象，并算出组织分组（BG）的跨行合并行数。
 *
 * BG 合并：分组名只出现在组内首行（其余行为空串），故以「非空分组名」为组起点，
 * 向下数到下一个非空分组名之前为止，即为该组的行数。
 */
export function buildMockResourceStats(): MockResourceStat[] {
  const rows: MockResourceStat[] = RAW.map((r) => {
    const o: any = {}
    STAT_COLS.forEach((c, i) => { o[c] = r[i] })
    return o as MockResourceStat
  })
  // 回填 bgSpan：组首行 = 本组行数，组内其余行 = 0（0 表示不渲染该格，由 naive 的 rowSpan 合并跳过）
  let i = 0
  while (i < rows.length) {
    if (!rows[i].bgGroup) { i += 1; continue }
    // 组起点在 i；向下找下一个「有分组名」的行，它就是下一组的起点
    let j = i + 1
    while (j < rows.length && !rows[j].bgGroup) j += 1
    rows[i].bgSpan = j - i
    for (let k = i + 1; k < j; k += 1) rows[k].bgSpan = 0
    i = j
  }
  return rows
}
