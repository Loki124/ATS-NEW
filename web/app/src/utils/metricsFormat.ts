/**
 * metricsFormat.ts — 指标管理（MetricsWorkspace）纯格式化 / 映射工具。
 *
 * 从 MetricsWorkspace.vue 的 <script setup> 中抽取而来，目的是：
 *   1) 把与组件状态无关的纯函数集中到可单测模块，补 Vitest 覆盖（项目纪律：god 组件须有单测）；
 *   2) 为后续把整页逻辑迁入 useMetricsWorkspace 组合式提供底层原子能力。
 *
 * 约定：
 *   - 不依赖组件级 reactive state（如 operatorCatalog / tplForm），保证纯函数可独立测试。
 *   - i18n 依赖通过 `t` 参数显式注入（I18nT 形如 vue-i18n 的 t），组件里用薄包装把 useI18n().t 传进来，
 *     既保持模板调用点不变，又让单测可用 identity-mock 验证「选键逻辑」而不依赖字典。
 */

import type { MetricDefinition, MetricTemplate, OptionItem } from '@/api/metrics'

export type I18nT = (key: string, named?: Record<string, unknown>) => string

