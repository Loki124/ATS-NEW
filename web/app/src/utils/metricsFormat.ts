/** 指标类型标签（原子 / 派生） */
export function kindLabel(t: I18nT, row: MetricDefinition): string {
  return row.kind === 'derived' ? t('metrics.tab.derived') : t('metrics.tab.atomic')
}

/** 入参实体：从数据源路径前缀推导真实实体 */
export function inputEntityLabel(t: I18nT, row: MetricDefinition): string {
  const ds = (row.dataSource || '') as string
  const prefix = ds.split('.')[0].toLowerCase()
  if (prefix === 'candidate') return t('metrics.detail.inputEntity.candidate')
  if (prefix === 'demand') return t('metrics.detail.inputEntity.demand')
  if (prefix === 'position') return t('metrics.detail.inputEntity.position')
  return t('metrics.detail.inputEntity.global')
}

/** 出参字段：数据源末级字段名 + 出参类型 */
export function outputFieldLabel(t: I18nT, row: MetricDefinition): string {
  const ds = (row.dataSource || '') as string
  const field = ds.includes('.') ? ds.slice(ds.lastIndexOf('.') + 1) : ''
  const type = returnTypeLabel(t, row.returnType)
  return field ? `${field} · ${type}` : type
}

/** 入参 / 出参 合并标签 */
export function inOutLabel(t: I18nT, row: MetricDefinition): string {
  return `${inputEntityLabel(t, row)} / ${outputFieldLabel(t, row)}`
}

/** 来源模块标签（优先业务板块名，回落粗粒度资源名） */
export function sourceModuleLabel(t: I18nT, row: MetricDefinition): string {
  if (row.moduleName) return row.moduleName
  return t(`metrics.module.${sourceModuleKey(row)}`)
}

/** 来源标记：自动生成 / 手工维护 */
export function originLabel(t: I18nT, row: MetricDefinition): string {
  return row.autoGenerated ? t('metrics.origin.auto') : t('metrics.origin.manual')
}

/** 日期边界展示文案（相对边界显示成「今天-30年」） */
export function dateBoundText(t: I18nT, b: unknown): string {
  if (!b || typeof b !== 'object') return '-'
  const bound = b as { type?: string; n?: unknown; unit?: string; date?: unknown }
  if (bound.type === 'relative') {
    const n = Number(bound.n ?? 0)
    const u = bound.unit || DATE_GRANULARITY_DEFAULT
    if (n === 0) return t('metrics.tpl.today')
    return `${t('metrics.tpl.today')}${n > 0 ? '+' : '-'}${Math.abs(n)}${u}`
  }
  return (bound.date as string) || '-'
}

