/** 类型徽标样式类：派生 → is-derived，原子 → is-atomic */
export function kindClass(row: Pick<MetricDefinition, 'kind'>): string {
  return row.kind === 'derived' ? 'is-derived' : 'is-atomic'
}

/** 枚举候选值（缺省兜底空数组） */
export function enumValuesOf(row: MetricDefinition): string[] {
  return (row.enumValues as string[] | undefined) || []
}

/** 是否自动生成（动态字段同步而来） */
export function isAutoGenerated(row: MetricDefinition): boolean {
  return row.autoGenerated === true
}

/** 来源模块 key：按实体前缀 / 派生归类，描述指标数据的来源子系统 */
export function sourceModuleKey(row: MetricDefinition): string {
  if (row.kind === 'derived') return 'derived'
  const prefix = (row.dataSource || '').split('.')[0].toLowerCase()
  if (prefix === 'candidate') return 'candidate'
  if (prefix === 'demand') return 'demand'
  if (prefix === 'position') return 'position'
  return 'other'
}

/** 模板参数范围文案（min/max/step） */
export function templateRange(row: MetricTemplate): string {
  const c = row.paramConfig
  if (!c || (c.min == null && c.max == null && c.step == null)) return '-'
  const parts: string[] = []
  if (c.min != null) parts.push(`min=${c.min}`)
  if (c.max != null) parts.push(`max=${c.max}`)
  if (c.step != null) parts.push(`step=${c.step}`)
  return parts.join(' / ')
}

/** 模板值域文案（分段 min~max） */
export function templateDomain(row: MetricTemplate): string {
  const segs = row.valueDomain?.segments
  if (!segs || !segs.length) return '-'
  return segs.map((s) => `${s.min ?? '*'}~${s.max ?? '*'}`).join('，')
}

/** 运算符展示符号表（键须与后端 UnifiedOperator.code 一致，大写） */
export const OP_SYMBOLS: Record<string, string> = {
  EQ: '=',
  NEQ: '≠',
  GT: '>',
  GTE: '≥',
  LT: '<',
  LTE: '≤',
  BETWEEN: '∈',
  IN: '∈',
  NOT_IN: '∉',
  CONTAINS: '⊇',
  NOT_CONTAINS: '⊉',
  REGEX_MATCH: '~',
}

/** 运算符 → 展示符号 */
export function opSymbol(value: string): string {
  return OP_SYMBOLS[String(value).toUpperCase()] || ''
}

/** 取首个未禁用的下拉项 value（预览默认值收敛） */
export function firstEnabledValue(opts: Array<{ value: unknown; disabled?: boolean }>): string {
  const o = opts.find((x) => !x.disabled)
  return o ? (o.value as string) : ''
}

/** 数值格式化：整数原样，小数保留两位 */
export function fmtNum(v: number): string {
  return Number.isInteger(v) ? String(v) : String(Math.round(v * 100) / 100)
}

/** 运算符 + 值 → 可读文本（如 `EQ: 10`） */
export function formatCondition(operator: string, value: unknown): string {
  if (value === null || value === undefined || value === '') return String(operator)
  const text = typeof value === 'object' ? JSON.stringify(value) : String(value)
  return `${operator}: ${text}`
}

/** ISO 时间 → `YYYY-MM-DD HH:mm`（非法回退原串） */
export function formatTime(iso?: string): string {
  if (!iso) return '-'
  const d = new Date(iso)
  if (isNaN(d.getTime())) return iso
  const pad = (n: number) => String(n).padStart(2, '0')
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}`
}

/** 把任意输入收敛为有限数或 null（值域分段边界校验用） */
export function segBound(v: unknown): number | null {
  if (v === null || v === undefined || v === '') return null
  const n = Number(v)
  return Number.isFinite(n) ? n : null
}

/** 版本历史变更类型 → 标签配色 */
export function verhTagType(
  kind: string,
): 'success' | 'info' | 'warning' | 'error' | 'default' {
  if (kind === 'create') return 'success'
  if (kind === 'rollback') return 'warning'
  if (kind === 'import') return 'info'
  return 'default'
}

