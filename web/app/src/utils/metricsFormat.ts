// 日期型出参：单位即「粒度」，值域即「日期区间约束」
// ===================================================================

export const DATE_GRANULARITIES = ['年', '月', '日']
export const DATE_GRANULARITY_DEFAULT = '日'

/** 按粒度步进推进日期（年/月用 setFullYear|setMonth，天然处理月末溢出） */
export function advanceDate(d: Date, n: number, unit: string): Date {
  const x = new Date(d.getTime())
  if (unit === '年') x.setFullYear(x.getFullYear() + n)
  else if (unit === '月') x.setMonth(x.getMonth() + n)
  else x.setDate(x.getDate() + n)
  return x
}

/** 边界 → Date（绝对按粒度补齐到合法 ISO；相对按今天偏移） */
export function resolveDateBound(b: unknown): Date | null {
  if (!b || typeof b !== 'object') return null
  const bound = b as { type?: string; n?: unknown; unit?: string; date?: unknown }
  if (bound.type === 'relative') {
    const n = Number(bound.n)
    if (!Number.isFinite(n)) return null
    return advanceDate(new Date(), n, bound.unit || DATE_GRANULARITY_DEFAULT)
  }
  const s = String(bound.date ?? '').trim()
  if (!s) return null
  const iso = /^\d{4}$/.test(s) ? `${s}-01-01` : /^\d{4}-\d{2}$/.test(s) ? `${s}-01` : s
  const d = new Date(iso)
  return Number.isNaN(d.getTime()) ? null : d
}

/** 按粒度格式化日期：年→YYYY，月→YYYY-MM，日→YYYY-MM-DD */
export function fmtDate(d: Date, g: string): string {
  const y = d.getFullYear()
  const m = String(d.getMonth() + 1).padStart(2, '0')
  const dd = String(d.getDate()).padStart(2, '0')
  if (g === '年') return String(y)
  if (g === '月') return `${y}-${m}`
  return `${y}-${m}-${dd}`
}

/** 参数配置摘要文案（min/max/step/前后缀/全部项） */
export function fmtParamConfig(c: unknown): string {
  const cfg = (c || {}) as {
    min?: unknown
    max?: unknown
    step?: unknown
    prefix?: string
    suffix?: string
    allOption?: boolean
  }
  if (
    !cfg ||
    (cfg.min == null && cfg.max == null && cfg.step == null && !cfg.prefix && !cfg.suffix && !cfg.allOption)
  ) {
    return '-'
  }
  const parts: string[] = []
  if (cfg.min != null) parts.push(`min=${cfg.min}`)
  if (cfg.max != null) parts.push(`max=${cfg.max}`)
  if (cfg.step != null) parts.push(`step=${cfg.step}`)
  if (cfg.prefix) parts.push(`前缀「${cfg.prefix}」`)
  if (cfg.suffix) parts.push(`后缀「${cfg.suffix}」`)
  if (cfg.allOption) parts.push('含「全部」选项')
  return parts.join(' / ') || '-'
}

/** 值域摘要文案（分段 min~max） */
export function fmtValueDomain(vd: unknown): string {
  const segs = (vd as { segments?: Array<{ min?: unknown; max?: unknown }> } | undefined)?.segments
  if (!segs || !segs.length) return '-'
  return segs.map((s) => `${s.min ?? '*'}~${s.max ?? '*'}`).join('，')
}

