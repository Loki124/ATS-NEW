import { describe, it, expect } from 'vitest'
import type { MetricDefinition, MetricTemplate, OptionItem } from '@/api/metrics'
import {
  kindClass,
  enumValuesOf,
  isAutoGenerated,
  sourceModuleKey,
  templateRange,
  templateDomain,
  OP_SYMBOLS,
  opSymbol,
  firstEnabledValue,
  fmtNum,
  formatCondition,
  formatTime,
  segBound,
  verhTagType,
  advanceDate,
  resolveDateBound,
  fmtDate,
  fmtParamConfig,
  fmtValueDomain,
  SNAP_FIELD_I18N,
  returnTypeLabel,
  paramTypeLabel,
  paramSchemaTypeLabel,
  kindLabel,
  inputEntityLabel,
  outputFieldLabel,
  inOutLabel,
  sourceModuleLabel,
  originLabel,
  dateBoundText,
  findOperatorLabel,
  metricRuleSceneLabel,
  metricRuleActionLabel,
  life1ChangeKindLabel,
  snapshotFieldLabel,
} from '../metricsFormat'

const t = (k: string) => k

const def = (over: Partial<MetricDefinition> = {}): MetricDefinition =>
  ({
    id: '1',
    code: 'AM0001',
    name: '面试次数',
    kind: 'atomic',
    dataSource: 'candidate.interview_count',
    returnType: 'number',
    autoGenerated: false,
    ...over,
  } as MetricDefinition)

const tpl = (over: Partial<MetricTemplate> = {}): MetricTemplate =>
  ({
    id: 'm1',
    code: 'MT0001',
    name: '模板',
    status: 'enabled',
    ...over,
  } as MetricTemplate)

describe('kindClass / enumValuesOf / isAutoGenerated', () => {
  it('kindClass: derived→is-derived, atomic→is-atomic', () => {
    expect(kindClass(def({ kind: 'derived' }))).toBe('is-derived')
    expect(kindClass(def({ kind: 'atomic' }))).toBe('is-atomic')
  })
  it('enumValuesOf: 缺省兜底空数组', () => {
    expect(enumValuesOf(def())).toEqual([])
    expect(enumValuesOf(def({ enumValues: ['a', 'b'] }))).toEqual(['a', 'b'])
  })
  it('isAutoGenerated: 仅 true 为真', () => {
    expect(isAutoGenerated(def({ autoGenerated: true }))).toBe(true)
    expect(isAutoGenerated(def({ autoGenerated: false }))).toBe(false)
    expect(isAutoGenerated(def())).toBe(false)
  })
})

describe('sourceModuleKey', () => {
  it('按实体前缀 / 派生归类', () => {
    expect(sourceModuleKey(def({ kind: 'derived' }))).toBe('derived')
    expect(sourceModuleKey(def({ dataSource: 'candidate.x' }))).toBe('candidate')
    expect(sourceModuleKey(def({ dataSource: 'demand.x' }))).toBe('demand')
    expect(sourceModuleKey(def({ dataSource: 'position.x' }))).toBe('position')
    expect(sourceModuleKey(def({ dataSource: 'global.x' }))).toBe('other')
    expect(sourceModuleKey(def({ dataSource: '' }))).toBe('other')
  })
})

describe('templateRange / templateDomain', () => {
  it('templateRange: 无 paramConfig 或不完整返回 -', () => {
    expect(templateRange(tpl())).toBe('-')
    expect(templateRange(tpl({ paramConfig: {} as any }))).toBe('-')
  })
  it('templateRange: 拼接 min/max/step', () => {
    expect(templateRange(tpl({ paramConfig: { min: 1, max: 10, step: 2 } as any }))).toBe(
      'min=1 / max=10 / step=2',
    )
    expect(templateRange(tpl({ paramConfig: { min: 1 } as any }))).toBe('min=1')
  })
  it('templateDomain: 无分段返回 -', () => {
    expect(templateDomain(tpl())).toBe('-')
    expect(templateDomain(tpl({ valueDomain: { segments: [] } }))).toBe('-')
  })
  it('templateDomain: 拼接分段', () => {
    expect(
      templateDomain(tpl({ valueDomain: { segments: [{ min: 1, max: 5 }, { min: 10, max: 20 }] } as any })),
    ).toBe('1~5，10~20')
  })
})

describe('opSymbol', () => {
  it('符号表覆盖主要运算符，未知返回空串', () => {
    expect(OP_SYMBOLS.EQ).toBe('=')
    expect(OP_SYMBOLS.BETWEEN).toBe('∈')
    expect(opSymbol('eq')).toBe('=')
    expect(opSymbol('NOT_IN')).toBe('∉')
    expect(opSymbol('unknown')).toBe('')
  })
})

describe('firstEnabledValue', () => {
  it('取首个未禁用项 value，全禁用返回空串', () => {
    expect(firstEnabledValue([{ value: 'a' }, { value: 'b', disabled: true }])).toBe('a')
    expect(firstEnabledValue([{ value: 'a', disabled: true }])).toBe('')
  })
})

describe('fmtNum', () => {
  it('整数原样，小数两位', () => {
    expect(fmtNum(5)).toBe('5')
    expect(fmtNum(5.0)).toBe('5')
    expect(fmtNum(1.234)).toBe('1.23')
    expect(fmtNum(10.5)).toBe('10.5')
  })
})

describe('formatCondition', () => {
  it('空值仅返回运算符', () => {
    expect(formatCondition('EQ', '')).toBe('EQ')
    expect(formatCondition('EQ', null)).toBe('EQ')
  })
  it('对象值 JSON 化', () => {
    expect(formatCondition('IN', ['a', 'b'])).toBe('IN: ["a","b"]')
    expect(formatCondition('EQ', 10)).toBe('EQ: 10')
  })
})

describe('formatTime', () => {
  it('空值 / 非法回退', () => {
    expect(formatTime()).toBe('-')
    expect(formatTime('not-a-date')).toBe('not-a-date')
  })
  it('格式化 ISO', () => {
    expect(formatTime('2026-03-04T05:06:00Z')).toMatch(/^2026-03-0[34] \d{2}:\d{2}$/)
  })
})

describe('segBound', () => {
  it('空 / 非数 → null，有限数 → number', () => {
    expect(segBound(null)).toBeNull()
    expect(segBound('')).toBeNull()
    expect(segBound('abc')).toBeNull()
    expect(segBound(3)).toBe(3)
    expect(segBound('3.5')).toBe(3.5)
  })
})

describe('verhTagType', () => {
  it('映射变更类型到标签配色', () => {
    expect(verhTagType('create')).toBe('success')
    expect(verhTagType('rollback')).toBe('warning')
    expect(verhTagType('import')).toBe('info')
    expect(verhTagType('update')).toBe('default')
  })
})

describe('日期工具', () => {
  it('advanceDate: 按粒度步进', () => {
    expect(advanceDate(new Date('2026-01-31'), 1, '年').getFullYear()).toBe(2027)
    // 用月中日期避免月末溢出（Jan 31 +1 月会溢出到 3 月，是 JS 原生行为，组件注释已说明「天然处理月末溢出」）
    expect(advanceDate(new Date('2026-01-15'), 1, '月').getMonth()).toBe(1) // 2月（0基）
    expect(advanceDate(new Date('2026-01-31'), 1, '日').getDate()).toBe(1)
  })
  it('resolveDateBound: 绝对 / 相对 / 非法', () => {
    const abs = resolveDateBound({ type: 'absolute', date: '2026' })
    expect(abs?.getFullYear()).toBe(2026)
    const rel = resolveDateBound({ type: 'relative', n: -30, unit: '年' })
    expect(rel).not.toBeNull()
    expect(resolveDateBound({ type: 'relative', n: 'x' })).toBeNull()
    expect(resolveDateBound(null)).toBeNull()
    expect(resolveDateBound({ type: 'absolute', date: '' })).toBeNull()
  })
  it('fmtDate: 按粒度格式化', () => {
    const d = new Date('2026-03-04T00:00:00')
    expect(fmtDate(d, '年')).toBe('2026')
    expect(fmtDate(d, '月')).toBe('2026-03')
    expect(fmtDate(d, '日')).toBe('2026-03-04')
  })
})

describe('fmtParamConfig / fmtValueDomain', () => {
  it('fmtParamConfig: 空 → -，完整拼接', () => {
    expect(fmtParamConfig(null)).toBe('-')
    expect(fmtParamConfig({})).toBe('-')
    expect(
      fmtParamConfig({ min: 1, max: 10, step: 2, prefix: '≥', suffix: '次', allOption: true }),
    ).toBe('min=1 / max=10 / step=2 / 前缀「≥」 / 后缀「次」 / 含「全部」选项')
  })
  it('fmtValueDomain: 空 → -，拼接分段', () => {
    expect(fmtValueDomain(null)).toBe('-')
    expect(fmtValueDomain({ segments: [] })).toBe('-')
    expect(fmtValueDomain({ segments: [{ min: 1, max: 5 }] })).toBe('1~5')
  })
})

describe('SNAP_FIELD_I18N', () => {
  it('覆盖业务可读字段', () => {
    expect(SNAP_FIELD_I18N.name).toBe('metrics.life1.field.name')
    expect(SNAP_FIELD_I18N.status).toBe('metrics.life1.field.status')
    expect(Object.keys(SNAP_FIELD_I18N).length).toBeGreaterThanOrEqual(10)
  })
})

describe('i18n 注入型标签', () => {
  it('returnTypeLabel: 映射 / 未知 / 空', () => {
    expect(returnTypeLabel(t, 'number')).toBe('pages.settings.MetricsWorkspace.s7')
    expect(returnTypeLabel(t, 'unknown')).toBe('unknown')
    expect(returnTypeLabel(t, undefined)).toBe('-')
  })
  it('paramTypeLabel: continuous/discrete/其它', () => {
    expect(paramTypeLabel(t, 'continuous')).toBe('metrics.paramType.continuous')
    expect(paramTypeLabel(t, 'discrete')).toBe('metrics.paramType.discrete')
    expect(paramTypeLabel(t, 'x')).toBe('-')
  })
  it('paramSchemaTypeLabel: 四类映射', () => {
    expect(paramSchemaTypeLabel(t, 'number')).toBe('metrics.detail.paramTypeNumber')
    expect(paramSchemaTypeLabel(t, 'select')).toBe('metrics.detail.paramTypeSelect')
    expect(paramSchemaTypeLabel(t, 'boolean')).toBe('metrics.detail.paramTypeBoolean')
    expect(paramSchemaTypeLabel(t, 'string')).toBe('metrics.detail.paramTypeString')
    expect(paramSchemaTypeLabel(t, 'x')).toBe('x')
  })
  it('kindLabel: 派生 / 原子', () => {
    expect(kindLabel(t, def({ kind: 'derived' }))).toBe('metrics.tab.derived')
    expect(kindLabel(t, def({ kind: 'atomic' }))).toBe('metrics.tab.atomic')
  })
  it('inputEntityLabel: 按数据源前缀', () => {
    expect(inputEntityLabel(t, def({ dataSource: 'candidate.x' }))).toBe('metrics.detail.inputEntity.candidate')
    expect(inputEntityLabel(t, def({ dataSource: 'demand.x' }))).toBe('metrics.detail.inputEntity.demand')
    expect(inputEntityLabel(t, def({ dataSource: 'position.x' }))).toBe('metrics.detail.inputEntity.position')
    expect(inputEntityLabel(t, def({ dataSource: 'global.x' }))).toBe('metrics.detail.inputEntity.global')
  })
  it('outputFieldLabel: 末级字段 + 类型', () => {
    expect(outputFieldLabel(t, def({ dataSource: 'candidate.interview_count', returnType: 'number' }))).toBe(
      'interview_count · pages.settings.MetricsWorkspace.s7',
    )
    expect(outputFieldLabel(t, def({ dataSource: 'candidate', returnType: 'number' }))).toBe(
      'pages.settings.MetricsWorkspace.s7',
    )
  })
  it('inOutLabel: 入参 / 出参 合并', () => {
    const r = def({ dataSource: 'candidate.interview_count', returnType: 'number' })
    expect(inOutLabel(t, r)).toBe(
      'metrics.detail.inputEntity.candidate / interview_count · pages.settings.MetricsWorkspace.s7',
    )
  })
  it('sourceModuleLabel: 优先 moduleName，回落 key 文案', () => {
    expect(sourceModuleLabel(t, def({ moduleName: '工作经历' }))).toBe('工作经历')
    expect(sourceModuleLabel(t, def({ dataSource: 'demand.x' }))).toBe('metrics.module.demand')
  })
  it('originLabel: 自动 / 手工', () => {
    expect(originLabel(t, def({ autoGenerated: true }))).toBe('metrics.origin.auto')
    expect(originLabel(t, def({ autoGenerated: false }))).toBe('metrics.origin.manual')
  })
  it('dateBoundText: 相对 / 绝对 / 空', () => {
    expect(dateBoundText(t, { type: 'relative', n: 0, unit: '年' })).toBe('metrics.tpl.today')
    expect(dateBoundText(t, { type: 'relative', n: -30, unit: '年' })).toBe('metrics.tpl.today-30年')
    expect(dateBoundText(t, { type: 'relative', n: 5, unit: '月' })).toBe('metrics.tpl.today+5月')
    expect(dateBoundText(t, { type: 'absolute', date: '2026-01-01' })).toBe('2026-01-01')
    expect(dateBoundText(t, null)).toBe('-')
  })
  it('findOperatorLabel: 命中目录 / 原值兜底', () => {
    const cat: OptionItem[] = [
      { label: '等于', value: 'EQ' },
      { label: '大于', value: 'GT' },
    ]
    expect(findOperatorLabel(cat, 'EQ')).toBe('等于')
    expect(findOperatorLabel(cat, 'NOPE')).toBe('NOPE')
  })
  it('metricRuleSceneLabel / metricRuleActionLabel', () => {
    expect(metricRuleSceneLabel(t, 'hire')).toBe('metrics.scene.hire')
    const opts = [
      { value: 'veto', labelKey: 'metrics.rule.action.veto' },
      { value: 'approve', labelKey: 'metrics.rule.action.approve' },
    ]
    expect(metricRuleActionLabel(t, opts, 'veto')).toBe('metrics.rule.action.veto')
    expect(metricRuleActionLabel(t, opts, 'unknown')).toBe('unknown')
  })
  it('life1ChangeKindLabel: 四类映射', () => {
    expect(life1ChangeKindLabel(t, 'create')).toBe('metrics.life1.changeKind.create')
    expect(life1ChangeKindLabel(t, 'update')).toBe('metrics.life1.changeKind.update')
    expect(life1ChangeKindLabel(t, 'rollback')).toBe('metrics.life1.changeKind.rollback')
    expect(life1ChangeKindLabel(t, 'import')).toBe('metrics.life1.changeKind.import')
    expect(life1ChangeKindLabel(t, 'weird')).toBe('weird')
  })
  it('snapshotFieldLabel: 已知字段走 i18n 键，未知原样', () => {
    expect(snapshotFieldLabel(t, 'name')).toBe('metrics.life1.field.name')
    expect(snapshotFieldLabel(t, 'unknown_field')).toBe('unknown_field')
  })
})
