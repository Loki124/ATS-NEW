/**
 * useMetricColumns.ts — 指标定义表 / 指标模板表的 n-data-table 列定义。
 *
 * 从 useMetricsWorkspace.ts 拆出（原 327–507 一段）。两张表的列定义是纯渲染函数：
 *   - 不发请求、不改状态，只根据行数据产出 h() 虚拟节点；
 *   - 外部依赖只有 operatorCatalog 与一组文案/事件回调，全部由 deps 显式注入。
 *
 * 🔴 为什么 KindIcon / OperatorBadge 走 deps 注入而不是在本文件 import：
 *   这两个组件的 import 按重构规格必须留在主逻辑层（useMetricsWorkspace.ts），
 *   否则主逻辑层对渲染组件的依赖归属就变了。故这里接收组件构造器作为参数由主 composable 传入，
 *   import 归属不变，而 181 行列定义体积移出主文件。
 *
 * 行为零变化：render 函数体与拆分前逐字一致。
 */
import { computed, h, type Component } from 'vue'
import { useI18n } from 'vue-i18n'
import { NButton, NTag, type DataTableColumns } from 'naive-ui'
import type { MetricDefinition, MetricTemplate, OptionItem } from '@/api/metrics'

export interface MetricColumnsDeps {
  /** 指标类型图标组件（由主 composable 从 @/components/metrics/KindIcon.vue import 后传入）。 */
  KindIcon: Component
  /** 运算符徽标组件（由主 composable 从 @/components/metrics/OperatorBadge.vue import 后传入）。 */
  OperatorBadge: Component
  operatorCatalog: { value: OptionItem[] }
  isAutoGenerated: (row: MetricDefinition) => boolean
  originLabel: (row: MetricDefinition) => string
  sourceModuleLabel: (row: MetricDefinition) => string
  returnTypeLabel: (type?: string) => string
  inputEntityLabel: (row: MetricDefinition) => string
  outputFieldLabel: (row: MetricDefinition) => string
  openDetail: (row: MetricDefinition) => void
  openTemplateEdit: (row: MetricTemplate) => void
  toggleTemplate: (row: MetricTemplate) => void
  openVersionHistory: (row: MetricTemplate) => void
  busyRowId: { value: string }
}

export function useMetricColumns(deps: MetricColumnsDeps) {
  const { t } = useI18n()
  const {
    KindIcon,
    OperatorBadge,
    operatorCatalog,
    isAutoGenerated,
    originLabel,
    sourceModuleLabel,
    returnTypeLabel,
    inputEntityLabel,
    outputFieldLabel,
    openDetail,
    openTemplateEdit,
    toggleTemplate,
    openVersionHistory,
    busyRowId,
  } = deps

  // ===== 指标定义表（n-data-table）列定义 =====
  const defColumns = computed<DataTableColumns<MetricDefinition>>(() => [
    {
      title: t('metrics.col.code'),
      key: 'code',
      width: 96,
      render: (row) => h('span', { class: 'ws-cell-code' }, row.code || '-'),
    },
    {
      title: t('metrics.col.name'),
      key: 'name',
      minWidth: 150,
      render: (row) => h('span', { class: 'ws-cell-name' }, row.name),
    },
    {
      title: t('metrics.col.origin'),
      key: 'origin',
      width: 104,
      render: (row) =>
        h(
          'span',
          {
            class: isAutoGenerated(row) ? 'ws-origin-tag is-auto' : 'ws-origin-tag is-manual',
          },
          originLabel(row),
        ),
    },
    {
      title: t('metrics.col.type'),
      key: 'kind',
      width: 72,
      render: (row) => h(KindIcon, { kind: row.kind, size: 18 }),
    },
    {
      title: t('metrics.col.sourceModule'),
      key: 'sourceModule',
      width: 140,
      render: (row) => h('span', { class: 'ws-cell-module' }, sourceModuleLabel(row)),
    },
    {
      title: t('metrics.col.returnType'),
      key: 'returnType',
      width: 96,
      render: (row) => h('span', { class: 'ws-cell-rt' }, returnTypeLabel(row.returnType)),
    },
    {
      title: t('metrics.col.inOutType'),
      key: 'inOut',
      minWidth: 220,
      render: (row) =>
        h('span', { class: 'ws-inout-cell' }, [
          h('span', { class: 'ws-inout-part' }, inputEntityLabel(row)),
          h('span', { class: 'ws-inout-sep' }, ' / '),
          h('span', { class: 'ws-inout-part' }, outputFieldLabel(row)),
        ]),
    },
    {
      title: t('metrics.col.operatorCount'),
      key: 'operators',
      width: 96,
      render: (row) => h(OperatorBadge, { value: row.supportedOperators, catalog: operatorCatalog.value }),
    },
  ])

  function defRowProps(row: MetricDefinition) {
    return {
      style: 'cursor:pointer',
      onClick: () => openDetail(row),
      onKeydown: (e: KeyboardEvent) => {
        if (e.key === 'Enter') openDetail(row)
      },
    }
  }

  // 模板行：整行可点击 → 打开编辑弹窗
  function tplRowProps(row: MetricTemplate) {
    return {
      style: 'cursor:pointer',
      onClick: () => openTemplateEdit(row),
      onKeydown: (e: KeyboardEvent) => {
        if (e.key === 'Enter') openTemplateEdit(row)
      },
    }
  }

  // ===== 指标模板表列定义 =====
  const tplColumns = computed<DataTableColumns<MetricTemplate>>(() => [
    {
      title: t('metrics.col.code'),
      key: 'code',
      width: 96,
      render: (row) => h('span', { class: 'ws-cell-code' }, row.code || '-'),
    },
    {
      title: t('metrics.col.name'),
      key: 'name',
      minWidth: 160,
      render: (row) => h('span', { class: 'ws-cell-name' }, row.name),
    },
    {
      title: t('metrics.col.metric'),
      key: 'metric',
      minWidth: 200,
      render: (row) =>
        h('span', { class: 'ws-metric-cell' }, [
          h(KindIcon, { kind: row.metricKind ?? 'atomic', size: 18 }),
          ' ',
          row.metricName ?? '-',
        ]),
    },
    {
      title: t('metrics.tpl.outputType'),
      key: 'dataType',
      width: 150,
      render: (row) =>
        h(
          'span',
          row.dataType ? `${returnTypeLabel(row.dataType)}${row.unit ? ` (${row.unit})` : ''}` : '-',
        ),
    },
    {
      title: t('metrics.col.operatorCount'),
      key: 'operators',
      width: 110,
      render: (row) => h(OperatorBadge, { value: row.operators, catalog: operatorCatalog.value }),
    },
    {
      title: t('metrics.col.status'),
      key: 'status',
      width: 90,
      render: (row) =>
        h(
          NTag,
          { size: 'small', type: row.status === 'enabled' ? 'success' : 'default' },
          { default: () => (row.status === 'enabled' ? t('metrics.status.enabled') : t('metrics.status.disabled')) },
        ),
    },
    {
      title: t('metrics.life1.versionColumn'),
      key: 'version',
      width: 80,
      render: (row) =>
        h(
          'span',
          { title: t('metrics.life1.versionCount', { n: row.versionCount ?? 0 }) },
          row.version ? `v${row.version}` : '-',
        ),
    },
    {
      title: t('metrics.col.action'),
      key: 'action',
      width: 250,
      render: (row) =>
        h('div', { class: 'ws-row-actions' }, [
          h(
            NButton,
            { size: 'small', quaternary: true, onClick: (e: MouseEvent) => { e.stopPropagation(); openTemplateEdit(row) } },
            { default: () => t('metrics.btn.edit') },
          ),
          h(
            NButton,
            {
              size: 'small',
              quaternary: true,
              loading: busyRowId.value === row.id,
              onClick: (e: MouseEvent) => { e.stopPropagation(); toggleTemplate(row) },
            },
            { default: () => (row.status === 'enabled' ? t('metrics.btn.disable') : t('metrics.btn.enable')) },
          ),
          h(
            NButton,
            {
              size: 'small',
              quaternary: true,
              onClick: (e: MouseEvent) => { e.stopPropagation(); openVersionHistory(row) },
            },
            { default: () => t('metrics.life1.versionHistory') },
          ),
        ]),
    },
  ])

  return {
    defColumns,
    defRowProps,
    tplColumns,
    tplRowProps,
  }
}
