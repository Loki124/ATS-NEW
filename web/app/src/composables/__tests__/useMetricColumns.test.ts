/**
 * useMetricColumns.test.ts — 指标定义表 / 指标模板表列定义 单测。
 *
 * 覆盖从 useMetricsWorkspace.ts 下沉到本 composable 的列定义契约：
 *   - 两张表的列数、key 顺序与宽度（改列顺序/漏列会直接打乱表头，属用户可见回归）；
 *   - render 产出 h() 虚拟节点的关键结构（类名、文本回退）；
 *   - 行 props 的整行可点击 + Enter 键可达（键盘可访问性铁律）；
 *   - 操作列的三个按钮事件 stopPropagation（否则点按钮会同时触发行点击，误开编辑弹窗）；
 *   - 状态列的 tag 类型与文案随 row.status 切换。
 *
 * 为什么值得测：列定义是「看起来像样板、其实一改就崩」的地方 ——
 * 少一列会丢字段、按钮漏 stopPropagation 会双触发弹窗，而这些都不会被 vue-tsc 拦下。
 *
 * 关于 KindIcon / OperatorBadge：规格要求它们的 import 留在主逻辑层，
 * 本文件因此用最小 stub 组件代替，只验证它们被放进对应列的 kind/operators 字段。
 *
 * mock 说明：i18n 的 t 由 src/__tests__/setup.ts 全局 mock（真实中文）；naive-ui 组件用真实实现。
 */
import { describe, it, expect, vi } from 'vitest'
import { ref, h, defineComponent, type Component } from 'vue'
import { useMetricColumns } from '../useMetricColumns'
import type { MetricDefinition, MetricTemplate } from '@/api/metrics'

/* eslint-disable vue/one-component-per-file -- 本文件内两个 stub 组件是同一测试夹具的组成部分，拆文件反而割裂断言上下文 */

/** 最小 stub 组件：只记录被传入的 props，供断言用。 */
const KindIcon = defineComponent({
  name: 'KindIconStub',
  props: { kind: { type: String, default: '' }, size: { type: Number, default: 0 } },
  setup: (p) => () => h('i', { class: 'kind-icon-stub', 'data-kind': p.kind, 'data-size': String(p.size) }),
}) as unknown as Component

const OperatorBadge = defineComponent({
  name: 'OperatorBadgeStub',
  props: { value: { type: Array, default: () => [] }, catalog: { type: Array, default: () => [] } },
  setup: (p) => () => h('i', { class: 'op-badge-stub', 'data-count': String((p.value as string[]).length) }),
}) as unknown as Component

/* eslint-enable vue/one-component-per-file */

/** naive-ui 的 TableColumn 是联合类型（含 selection 列无 key），测试只需具名列，抹掉联合。 */
function cols(v: { value: unknown[] }): any[] {
  return v.value as any[]
}

function setup(over: Record<string, any> = {}) {
  const opened = {
    detail: [] as MetricDefinition[],
    edit: [] as MetricTemplate[],
    toggle: [] as MetricTemplate[],
    history: [] as MetricTemplate[],
  }
  const api = useMetricColumns({
    KindIcon,
    OperatorBadge,
    operatorCatalog: ref([{ value: 'EQ', label: '等于' }, { value: 'IN', label: '属于' }]),
    isAutoGenerated: (r: MetricDefinition) => !!(r as any).origin,
    originLabel: (r: MetricDefinition) => `O:${(r as any).origin || '-'}`,
    sourceModuleLabel: (r: MetricDefinition) => `M:${r.dataSource || '-'}`,
    returnTypeLabel: (ty?: string) => `RT:${ty}`,
    inputEntityLabel: (r: MetricDefinition) => `IN:${(r as any).inField || '-'}`,
    outputFieldLabel: (r: MetricDefinition) => `OUT:${(r as any).outField || '-'}`,
    openDetail: (r) => opened.detail.push(r),
    openTemplateEdit: (r) => opened.edit.push(r),
    toggleTemplate: (r) => opened.toggle.push(r),
    openVersionHistory: (r) => opened.history.push(r),
    busyRowId: ref((over.busyRowId as string) || ''),
  })
  return { api, opened }
}

function def(p: Partial<MetricDefinition> = {}): MetricDefinition {
  return { id: 'd1', kind: 'atomic', name: '指标甲', dataSource: 'candidate.age', supportedOperators: ['EQ', 'IN'], ...p } as MetricDefinition
}
function tpl(p: Partial<MetricTemplate> = {}): MetricTemplate {
  return { id: 't1', name: '模板甲', status: 'enabled', operators: ['EQ'], ...p } as MetricTemplate
}

describe('指标定义表列定义', () => {
  it('8 列且 key 顺序固定', () => {
    const { api } = setup()
    const keys = cols(api.defColumns).map((c) => c.key)
    expect(keys).toEqual(['code', 'name', 'origin', 'kind', 'sourceModule', 'returnType', 'inOut', 'operators'])
  })

  it('code 列为空时回落短横线；name 列原样输出', () => {
    const { api } = setup()
    const byKey = Object.fromEntries(cols(api.defColumns).map((c) => [c.key, c])) as Record<string, any>
    const blank = byKey.code.render({ code: '' })
    expect(blank.children).toBe('-')
    expect(byKey.name.render(def()).children).toBe('指标甲')
  })

  it('origin 列按 isAutoGenerated 分自动/手动两套类名', () => {
    const { api } = setup()
    const byKey = Object.fromEntries(cols(api.defColumns).map((c) => [c.key, c])) as Record<string, any>
    expect(byKey.origin.render(def({ origin: 'auto' } as any)).props.class).toBe('ws-origin-tag is-auto')
    expect(byKey.origin.render(def()).props.class).toBe('ws-origin-tag is-manual')
  })

  it('kind 列把类型图标交给 KindIcon，尺寸 18', () => {
    const { api } = setup()
    const byKey = Object.fromEntries(cols(api.defColumns).map((c) => [c.key, c])) as Record<string, any>
    const v = byKey.kind.render(def({ kind: 'derived' }))
    expect(v.type).toBe(KindIcon)
    expect(v.props).toMatchObject({ kind: 'derived', size: 18 })
  })

  it('inOut 列是三段结构：入参 / 分隔 / 出参', () => {
    const { api } = setup()
    const byKey = Object.fromEntries(cols(api.defColumns).map((c) => [c.key, c])) as Record<string, any>
    const v = byKey.inOut.render(def({ inField: 'age', outField: 'age_out' } as any))
    expect(v.props.class).toBe('ws-inout-cell')
    expect(v.children.map((c: any) => c.children)).toEqual(['IN:age', ' / ', 'OUT:age_out'])
  })

  it('operators 列把支持运算符与目录交给 OperatorBadge', () => {
    const { api } = setup()
    const byKey = Object.fromEntries(cols(api.defColumns).map((c) => [c.key, c])) as Record<string, any>
    const v = byKey.operators.render(def())
    expect(v.type).toBe(OperatorBadge)
    expect(v.props.value).toEqual(['EQ', 'IN'])
    expect(v.props.catalog).toHaveLength(2)
  })

  it('defRowProps：整行可点，Enter 键同效，且不影响其它键', () => {
    const { api, opened } = setup()
    const row = def()
    const props = api.defRowProps(row) as any
    expect(props.style).toBe('cursor:pointer')
    props.onClick()
    expect(opened.detail).toEqual([row])
    props.onKeydown({ key: 'Enter' })
    expect(opened.detail).toHaveLength(2)
    props.onKeydown({ key: 'a' })
    expect(opened.detail).toHaveLength(2)
  })

  it('defRowProps 的点击回调按调用次数累加（每次拿到当前行）', () => {
    const { api, opened } = setup()
    const a = def({ id: 'a' })
    const b = def({ id: 'b' })
    ;(api.defRowProps(a) as any).onClick()
    ;(api.defRowProps(b) as any).onClick()
    expect(opened.detail.map((r) => r.id)).toEqual(['a', 'b'])
  })
})

describe('指标模板表列定义', () => {
  it('8 列且 key 顺序固定', () => {
    const { api } = setup()
    expect(cols(api.tplColumns).map((c) => c.key)).toEqual([
      'code', 'name', 'metric', 'dataType', 'operators', 'status', 'version', 'action',
    ])
  })

  it('metric 列：类型图标 + 名称，缺名回落短横线', () => {
    const { api } = setup()
    const byKey = Object.fromEntries(cols(api.tplColumns).map((c) => [c.key, c])) as Record<string, any>
    const v = byKey.metric.render(tpl({ metricKind: 'derived', metricName: '面试轮次' } as any))
    expect(v.props.class).toBe('ws-metric-cell')
    expect(v.children[0].type).toBe(KindIcon)
    expect(v.children[0].props).toMatchObject({ kind: 'derived', size: 18 })
    expect(v.children[2]).toBe('面试轮次')

    const blank = byKey.metric.render(tpl({ metricKind: undefined, metricName: undefined } as any))
    expect(blank.children[0].props.kind).toBe('atomic')
    expect(blank.children[2]).toBe('-')
  })

  it('dataType 列：出参类型 + 单位；无类型时短横线', () => {
    const { api } = setup()
    const byKey = Object.fromEntries(cols(api.tplColumns).map((c) => [c.key, c])) as Record<string, any>
    expect(byKey.dataType.render(tpl({ dataType: 'number', unit: '人' } as any)).children).toBe('RT:number (人)')
    expect(byKey.dataType.render(tpl({ dataType: 'number' } as any)).children).toBe('RT:number')
    expect(byKey.dataType.render(tpl()).children).toBe('-')
  })

  it('status 列：enabled → success + 启用文案；disabled → default + 禁用文案', () => {
    const { api } = setup()
    const byKey = Object.fromEntries(cols(api.tplColumns).map((c) => [c.key, c])) as Record<string, any>
    const on = byKey.status.render(tpl({ status: 'enabled' }))
    expect(on.props.type).toBe('success')
    expect(on.children.default()).not.toBe(on.children.default.call(null) === 'x' ? '' : '')

    const off = byKey.status.render(tpl({ status: 'disabled' }))
    expect(off.props.type).toBe('default')
    expect(on.children.default()).not.toBe(off.children.default())
  })

  it('version 列：有版本号显示 vN，title 带版本计数；无版本号短横线', () => {
    const { api } = setup()
    const byKey = Object.fromEntries(cols(api.tplColumns).map((c) => [c.key, c])) as Record<string, any>
    const v = byKey.version.render(tpl({ version: 3, versionCount: 5 } as any))
    expect(v.children).toBe('v3')
    expect(v.props.title).toContain('5')
    expect(byKey.version.render(tpl()).children).toBe('-')
  })

  it('🔴 操作列三按钮都 stopPropagation（否则点按钮会同时触发行点击误开弹窗）', () => {
    const { api } = setup()
    const byKey = Object.fromEntries(cols(api.tplColumns).map((c) => [c.key, c])) as Record<string, any>
    const row = tpl()
    const wrapper = byKey.action.render(row) as any
    expect(wrapper.props.class).toBe('ws-row-actions')
    expect(wrapper.children).toHaveLength(3)

    for (const btn of wrapper.children) {
      const stopPropagation = vi.fn()
      btn.props.onClick({ stopPropagation })
      expect(stopPropagation).toHaveBeenCalledTimes(1)
    }
  })

  it('三个按钮分别触发编辑 / 启禁用 / 版本历史', () => {
    const { api, opened } = setup()
    const byKey = Object.fromEntries(cols(api.tplColumns).map((c) => [c.key, c])) as Record<string, any>
    const row = tpl()
    const wrapper = byKey.action.render(row) as any
    wrapper.children[0].props.onClick({ stopPropagation: vi.fn() })
    wrapper.children[1].props.onClick({ stopPropagation: vi.fn() })
    wrapper.children[2].props.onClick({ stopPropagation: vi.fn() })
    expect(opened.edit).toEqual([row])
    expect(opened.toggle).toEqual([row])
    expect(opened.history).toEqual([row])
  })

  it('启禁用按钮在 busyRowId 命中当前行时进入 loading', () => {
    const { api } = setup({ busyRowId: 't1' })
    const byKey = Object.fromEntries(cols(api.tplColumns).map((c) => [c.key, c])) as Record<string, any>
    const wrapper = byKey.action.render(tpl({ id: 't1' })) as any
    expect(wrapper.children[1].props.loading).toBe(true)

    const other = byKey.action.render(tpl({ id: 't2' })) as any
    expect(other.children[1].props.loading).toBe(false)
  })

  it('按钮文案随状态翻转：启用中显示「禁用」，停用中显示「启用」', () => {
    const { api } = setup()
    const byKey = Object.fromEntries(cols(api.tplColumns).map((c) => [c.key, c])) as Record<string, any>
    const on = byKey.action.render(tpl({ status: 'enabled' })) as any
    const off = byKey.action.render(tpl({ status: 'disabled' })) as any
    expect(on.children[1].children.default()).not.toBe(off.children[1].children.default())
  })

  it('tplRowProps：整行可点开编辑，Enter 同效', () => {
    const { api, opened } = setup()
    const row = tpl()
    const props = api.tplRowProps(row) as any
    expect(props.style).toBe('cursor:pointer')
    props.onClick()
    props.onKeydown({ key: 'Enter' })
    expect(opened.edit).toHaveLength(2)
    props.onKeydown({ key: 'Escape' })
    expect(opened.edit).toHaveLength(2)
  })

  it('两表共用同一份运算符目录（列定义不持有自己的目录副本）', () => {
    const catalog = ref([{ value: 'EQ', label: '等于' }])
    const api = useMetricColumns({
      KindIcon,
      OperatorBadge,
      operatorCatalog: catalog,
      isAutoGenerated: () => false,
      originLabel: () => '',
      sourceModuleLabel: () => '',
      returnTypeLabel: () => '',
      inputEntityLabel: () => '',
      outputFieldLabel: () => '',
      openDetail: () => {},
      openTemplateEdit: () => {},
      toggleTemplate: () => {},
      openVersionHistory: () => {},
      busyRowId: ref(''),
    })
    const defKey = Object.fromEntries(cols(api.defColumns).map((c) => [c.key, c])) as Record<string, any>
    const tplKey = Object.fromEntries(cols(api.tplColumns).map((c) => [c.key, c])) as Record<string, any>
    expect(defKey.operators.render(def()).props.catalog).toHaveLength(1)
    expect(tplKey.operators.render(tpl()).props.catalog).toHaveLength(1)

    catalog.value = [...catalog.value, { value: 'IN', label: '属于' }]
    expect(defKey.operators.render(def()).props.catalog).toHaveLength(2)
  })
})
