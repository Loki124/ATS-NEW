    segs.forEach((s: any, i: number) => {
      if (s.step === null || s.step === undefined || s.step === '') { issues[i] = t('metrics.tpl.domainStepRequired'); return }
      const st = Number(s.step)
      if (!Number.isFinite(st) || !Number.isInteger(st) || st <= 0) { issues[i] = t('metrics.tpl.domainStepPositiveInt'); return }
      const from = resolveDateBound(s.from)
      const to = resolveDateBound(s.to)
      if (!from && !to) { issues[i] = t('metrics.tpl.domainBoundRequired'); return }
      for (const b of [s.from, s.to]) {
        if (b?.type === 'relative' && (b.n === null || b.n === undefined || b.n === '')) {
          issues[i] = t('metrics.tpl.domainRelativeRequired')
          return
        }
      }
      if (from && to && from.getTime() >= to.getTime()) { issues[i] = t('metrics.tpl.domainFromBeforeTo'); return }
    })
    const ranged = segs
      .map((s: any, i: number) => ({ i, from: resolveDateBound(s.from), to: resolveDateBound(s.to) }))
      .filter((b) => b.from && b.to)
      .sort((a, b) => (a.from as Date).getTime() - (b.from as Date).getTime())
    for (let k = 1; k < ranged.length; k++) {
      if ((ranged[k].from as Date).getTime() <= (ranged[k - 1].to as Date).getTime() && !issues[ranged[k].i]) {
        issues[ranged[k].i] = t('metrics.tpl.domainOverlap')
      }
    }
    return issues
