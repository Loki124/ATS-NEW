  function onTemplateMetricChange() {
    const d = selectedTemplateDefinition.value
    tplForm.value.unit = isDateOutput.value ? DATE_GRANULARITY_DEFAULT : ((d?.units && d.units[0]) || d?.unit || '')
    const segs = tplForm.value.valueDomain?.segments || []
    const hasNumeric = segs.some((s: any) => s && (s.min !== undefined || s.max !== undefined))
    const hasDate = segs.some((s: any) => s && (s.from || s.to))
    if ((isDateOutput.value && hasNumeric) || (isNumberOutput.value && hasDate) || (isEnumOutput.value || isTextOutput.value)) {
      tplForm.value.valueDomain = { segments: [] }
    }
    // 🔴 实体引用型：切换到人员/部门指标时，用 kind 结构重置值域（默认取第一个选取方式）
    if (isEntityOutput.value) {
      tplForm.value.valueDomain = { kind: entityKind.value, options: [] }
      void ensureEntityOptions()
    }
    // 切指标后草稿行同步复位（人员/部门的取值方式不同，残留草稿会错配）
    resetEntityDraft()
    if (isEnumOutput.value) {
      tplForm.value.paramEnums = [...(d?.enumValues || [])]
    } else {
      tplForm.value.paramEnums = []
    }
    tplForm.value.paramUnit = (d?.paramUnits && d.paramUnits[0]) || ''
    if (d?.supportedOperators?.length) {
      const ops = [...d.supportedOperators] as string[]
      tplForm.value.operators = isTextOutput.value ? ops.filter((op) => !SET_OPERATORS.includes(op)) : ops
    } else {
      tplForm.value.operators = []
    }
    if (!showTemplateParamConfig.value) {
      tplForm.value.paramConfig = { min: null, max: null, step: null, prefix: '', suffix: '', allOption: false, allText: '全部工作经历' }
      tplForm.value.calcParams = {}
    } else if (selectedTemplateDefinition.value?.paramSchema?.length) {
      for (const p of selectedTemplateDefinition.value.paramSchema) {
        if (tplForm.value.calcParams[p.key] === undefined && p.default !== undefined) {
          tplForm.value.calcParams[p.key] = p.default
        }
      }
    }
  }

