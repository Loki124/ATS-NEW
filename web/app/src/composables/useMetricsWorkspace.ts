  function computeDateDomain(): { items: { text: string; value: string }[]; total: number } {
    const g = currentOutputUnit.value
    const items: { text: string; value: string }[] = []
    let total = 0
    for (const seg of tplForm.value.valueDomain?.segments || []) {
      const from = resolveDateBound(seg.from)
      const to = resolveDateBound(seg.to)
      if (!from && !to) continue
      let st = Number(seg.step)
      if (!st || st < 1) st = 1
      const su = seg.stepUnit || g
      if (!from || !to) {
        const edge = (from || to) as Date
        total += 1
        if (items.length < DATE_ENUM_LIMIT) {
          items.push({
            text: from ? `${fmtDate(edge, g)}起` : `${fmtDate(edge, g)}及以前`,
            value: fmtDate(edge, '日'),
          })
        }
        continue
      }
      if (from.getTime() > to.getTime()) continue
      for (let d = from; d.getTime() <= to.getTime(); d = advanceDate(d, st, su)) {
        total += 1
        if (items.length < DATE_ENUM_LIMIT) items.push({ text: fmtDate(d, g), value: fmtDate(d, '日') })
        if (total >= 5000) break
      }
    }
    return { items, total }
  }

  function buildDomainItems(): { text: string; value: string }[] {
    const d = selectedTemplateDefinition.value
    const isDiscrete = d?.paramType === 'discrete'
    const u = tplForm.value.unit || d?.unit || ''
    const out: { text: string; value: string }[] = []
    for (const seg of tplForm.value.valueDomain?.segments || []) {
      const mn = Number(seg.min)
      const mxRaw = seg.max === null || seg.max === undefined || seg.max === '' ? null : Number(seg.max)
      let st = Number(seg.step)
      if (!st || st <= 0) st = isDiscrete ? 1 : 0.5
      if (!Number.isFinite(mn) || !(st > 0)) continue
      if (mxRaw === null || !Number.isFinite(mxRaw)) {
        out.push({ text: `${fmtNum(mn)}${u}以上`, value: `${fmtNum(mn)}+` })
        continue
      }
      if (mxRaw <= mn) continue
      for (let v = mn; v <= mxRaw + 1e-9; v += st) {
        out.push({ text: `${fmtNum(v)}${u}`, value: fmtNum(v) })
      }
    }
    return out
  }
