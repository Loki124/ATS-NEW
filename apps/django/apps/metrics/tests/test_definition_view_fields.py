"""指标定义视图的来源与板块字段（2026-10 全量治理配套）。

回填后「指标定义」里混着两类指标：
    - auto_generated=True  —— 由动态字段自动生成，删除字段不应牵连它
    - auto_generated=False —— 手工维护（含 58 条历史种子）
若不标出来，用户无从判断哪些能删、哪些是自己配的；而所属板块正是本次
清洗建立的东西，不返回就等于白做。
"""
import pytest

from apps.metrics.models import AtomicMetric
from apps.metrics.views import MetricDefinitionViewSet

pytestmark = pytest.mark.django_db


def _module(resource, code, name):
    """复用 0023 清洗迁移已建的板块；不存在才建（(resource, code) 有唯一约束）。"""
    from apps.dynamic_field.models import FieldModule

    mod = FieldModule.objects.filter(resource=resource, code=code).first()
    if mod is None:
        mod = FieldModule.objects.create(
            id=f'tv_{resource}_{code}', resource=resource, code=code, name=name,
        )
    return mod


def _rows():
    resp = MetricDefinitionViewSet().get(None)
    body = resp.data if hasattr(resp, 'data') else resp
    return body.get('data', body) if isinstance(body, dict) else body


def test_definition_exposes_auto_generated_flag():
    auto = AtomicMetric.objects.create(
        name='回填用例-自动', source_path='candidate._sync_flag_case',
        data_type='string', status='enabled', auto_generated=True,
    )
    hand = AtomicMetric.objects.create(
        name='回填用例-手工', source_path='candidate._sync_hand_case',
        data_type='string', status='enabled', auto_generated=False,
    )
    rows = {r['name']: r for r in _rows()}
    assert rows['回填用例-自动']['autoGenerated'] is True
    assert rows['回填用例-手工']['autoGenerated'] is False
    assert rows[auto.name]['code'].startswith('AM')
    assert rows[hand.name]['code'].startswith('AM')


def test_definition_resolves_module_name_from_dynamic_field():
    """板块名通过 source_path 反查动态字段，批量查询不产生 N+1。"""
    from apps.dynamic_field.models import DynamicField

    module = _module('Candidate', 'candidate', '候选人信息')
    DynamicField.objects.create(
        resource='Candidate', field_key='module_case_field', label='板块用例字段',
        field_type='TEXT', module=module, options=[],
    )
    AtomicMetric.objects.create(
        name='板块用例指标', source_path='candidate.module_case_field',
        data_type='string', status='enabled', auto_generated=True,
    )

    rows = {r['name']: r for r in _rows()}
    assert rows['板块用例指标']['moduleName'] == '候选人信息'


def test_definition_module_name_empty_for_non_dynamic_metric():
    """主表种子指标没有对应动态字段，板块留空而不是报错。"""
    AtomicMetric.objects.create(
        name='无板块用例指标', source_path='candidate.not_a_dynamic_field',
        data_type='string', status='enabled', auto_generated=False,
    )
    rows = {r['name']: r for r in _rows()}
    assert rows['无板块用例指标']['moduleName'] == ''


def test_dynamic_field_lookup_is_case_normalized():
    """路径前缀是 resource 小写（candidate/demand/position），大小写写错就不该匹配。"""
    from apps.dynamic_field.models import DynamicField

    module = _module('Demand', 'Demand', '招聘需求')
    DynamicField.objects.create(
        resource='Demand', field_key='case_norm_field', label='大小写用例',
        field_type='TEXT', module=module, options=[],
    )
    AtomicMetric.objects.create(
        name='大小写用例指标', source_path='demand.case_norm_field',
        data_type='string', status='enabled', auto_generated=True,
    )
    rows = {r['name']: r for r in _rows()}
    assert rows['大小写用例指标']['moduleName'] == '招聘需求'